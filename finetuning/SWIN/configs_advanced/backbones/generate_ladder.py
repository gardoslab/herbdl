"""ConvNeXt on the 64k ladder rung (supplement): training configs and feature-pass configs.

Training: ladder/convnext_n64k_<loss>.yml from the Part 4 base recipe (convnext_<loss>.yml; NormFace
from the ArcFace config with m=0). Changes: the 64k rung's data (ladder/n64k_{train,val}.json, image
column `filepath`), the ladder's fixed budget of 131,250 optimizer steps (= 50 epochs of the base
data at batch 256, so the same compute as on 15.5k; about 14.9 epochs of the 64k rung), evaluation
every 26,250 steps, outputs under BACKBONES/LADDER_N64K_<loss>. ArcFace's margin warm-up is
shortened from 5 epochs to 1, because 5 epochs of the 64k rung would be a third of training; 1 epoch
(8,786 steps) is closest to the base run's warm-up length (13,125 steps).
Feature passes: ladder/geom/convnext_n64k_<loss>_{val,train}.yml (eval-only, features + predictions
to LADDER_GEOM{,_TRAIN}/convnext_n64k_<loss>).
Run: python finetuning/SWIN/configs_advanced/backbones/generate_ladder.py
"""
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = "/projectnb/herbdl/workspaces/faridkar/herbdl/finetuning/output"
DATA = "/projectnb/herbdl/workspaces/faridkar/herbdl/data/ladder"
os.makedirs(f"{HERE}/ladder/geom", exist_ok=True)
for loss in ("cosine_m0", "dbm", "arcface"):
    c = yaml.safe_load(open(f"{HERE}/convnext_{loss.replace('cosine_m0', 'arcface')}.yml"))
    lr = c["loss_registry"]
    if loss == "cosine_m0":
        lr["head_kwargs"]["m"] = 0.0
        lr.pop("margin_warmup_epochs", None)
    elif loss == "arcface":
        lr["margin_warmup_epochs"] = 1
    d, t = c["data"], c["training"]
    d.update(train_file=f"{DATA}/n64k_train.json", validation_file=f"{DATA}/n64k_val.json", image_column_name="filepath")
    out = f"{OUT}/BACKBONES/LADDER_N64K_{loss.upper()}"
    t.update(output_dir=out, logging_dir=out, max_steps=131250, eval_steps=26250, resume_from_checkpoint="newest",
             overwrite_output_dir=False)
    w = c["wandb"]
    w.update(run_group="LADDER_CONVNEXT_N64K", run_name=f"LADDER_CONVNEXT_N64K_{loss.upper()}",
             run_id=f"ladder_convnext_n64k_{loss}")
    c["custom"]["run_notes"] = (f"ConvNeXt-Base with {loss} on the 64k ladder rung, Part 4 recipe, "
                                "fixed 131,250-step budget (supplement).")
    name = f"convnext_n64k_{loss}"
    open(f"{HERE}/ladder/{name}.yml", "w").write(
        f"# GENERATED by generate_ladder.py: {name} (training)\n" + yaml.safe_dump(c, sort_keys=False))
    for split in ("val", "train"):
        e = yaml.safe_load(yaml.safe_dump(c))
        root = f"{OUT}/SWIN/LADDER_GEOM" + ("" if split == "val" else "_TRAIN") + f"/{name}"
        e["training"].update(do_train=False, do_eval=True, report_to="none", resume_from_checkpoint=None,
                             output_dir=root, logging_dir=root)
        if split == "train":
            e["data"]["validation_file"] = f"{DATA}/n64k_train.json"
        e["wandb"]["enabled"] = False
        e["custom"]["run_notes"] = f"Eval-only feature pass of {name} on the {split} split."
        e["evaluation"] = {"init_weights": f"{out}/model.safetensors",
                           "predictions_path": f"{root}/predictions.npz", "features_path": f"{root}/features.npy"}
        open(f"{HERE}/ladder/geom/{name}_{split}.yml", "w").write(
            f"# GENERATED by generate_ladder.py: {name}, {split} feature pass\n" + yaml.safe_dump(e, sort_keys=False))
    print(name)
