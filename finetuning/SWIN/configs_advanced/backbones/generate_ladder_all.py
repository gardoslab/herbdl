"""ConvNeXt and DINOv2 on the 32k and 64k ladder rungs (supplement): training and feature-pass configs.

Extends generate_ladder.py (ConvNeXt, 64k) to both backbones and both larger rungs, with NormFace
(ArcFace config with m=0), DBM and ArcFace. Each backbone keeps its Part 4 recipe; only the data and
the training length change:
  data          ladder/<rung>_{train,val}.json, image column `filepath`
  budget        the ladder's fixed image budget, 131,250 steps x 256 images = 33.6M images:
                ConvNeXt (batch 256) 131,250 steps, DINOv2 (batch 128) 262,500 steps
  evaluation    every 26,250 (ConvNeXt) / 52,500 (DINOv2) steps
  ArcFace warm-up  the base runs ramp the margin over 5 base epochs (13,125 / 26,245 steps); here it is
                set to the whole number of rung epochs closest to that length: 2 at 32k, 1 at 64k
  outputs       BACKBONES/LADDER_<RUNG>_<LOSS> (ConvNeXt, as in generate_ladder.py),
                BACKBONES/LADDER_DINOV2_<RUNG>_<LOSS> (DINOv2)
Feature passes: ladder/geom/<backbone>_<rung>_<loss>_{val,train}.yml -> LADDER_GEOM{,_TRAIN}/<same name>.
Run: python finetuning/SWIN/configs_advanced/backbones/generate_ladder_all.py
"""
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = "/projectnb/herbdl/workspaces/faridkar/herbdl/finetuning/output"
DATA = "/projectnb/herbdl/workspaces/faridkar/herbdl/data/ladder"
TRAIN_IMAGES = {"n32k": 1667994, "n64k": 2249230}
BASE = {"convnext": {"batch": 256, "steps": 131250, "eval": 26250, "warmup_steps": 5 * 2625},
        "dinov2": {"batch": 128, "steps": 262500, "eval": 52500, "warmup_steps": 5 * 5249}}
os.makedirs(f"{HERE}/ladder/geom", exist_ok=True)
for bb, b in BASE.items():
    for rung in ("n32k", "n64k"):
        for loss in ("cosine_m0", "dbm", "arcface"):
            c = yaml.safe_load(open(f"{HERE}/{bb}_{loss.replace('cosine_m0', 'arcface')}.yml"))
            lr = c["loss_registry"]
            if loss == "cosine_m0":
                lr["head_kwargs"]["m"] = 0.0
                lr.pop("margin_warmup_epochs", None)
            elif loss == "arcface":
                per_epoch = TRAIN_IMAGES[rung] / b["batch"]
                lr["margin_warmup_epochs"] = max(1, round(b["warmup_steps"] / per_epoch))
            d, t = c["data"], c["training"]
            d.update(train_file=f"{DATA}/{rung}_train.json", validation_file=f"{DATA}/{rung}_val.json",
                     image_column_name="filepath")
            tag = f"LADDER_{rung.upper()}_{loss.upper()}" if bb == "convnext" else f"LADDER_DINOV2_{rung.upper()}_{loss.upper()}"
            out = f"{OUT}/BACKBONES/{tag}"
            t.update(output_dir=out, logging_dir=out, max_steps=b["steps"], eval_steps=b["eval"],
                     resume_from_checkpoint="newest", overwrite_output_dir=False)
            c["wandb"].update(run_group=f"LADDER_{bb.upper()}_{rung.upper()}", run_name=f"LADDER_{bb.upper()}_{rung.upper()}_{loss.upper()}",
                              run_id=f"ladder_{bb}_{rung}_{loss}")
            c["custom"]["run_notes"] = (f"{bb} with {loss} on the {rung} ladder rung, Part 4 recipe, fixed image budget "
                                        f"({b['steps']:,} steps at batch {b['batch']}) (supplement).")
            name = f"{bb}_{rung}_{loss}"
            open(f"{HERE}/ladder/{name}.yml", "w").write(
                f"# GENERATED by generate_ladder_all.py: {name} (training)\n" + yaml.safe_dump(c, sort_keys=False))
            for split in ("val", "train"):
                e = yaml.safe_load(yaml.safe_dump(c))
                root = f"{OUT}/SWIN/LADDER_GEOM" + ("" if split == "val" else "_TRAIN") + f"/{name}"
                e["training"].update(do_train=False, do_eval=True, report_to="none", resume_from_checkpoint=None,
                                     output_dir=root, logging_dir=root)
                if split == "train":
                    e["data"]["validation_file"] = f"{DATA}/{rung}_train.json"
                e["wandb"]["enabled"] = False
                e["custom"]["run_notes"] = f"Eval-only feature pass of {name} on the {split} split."
                e["evaluation"] = {"init_weights": f"{out}/model.safetensors",
                                   "predictions_path": f"{root}/predictions.npz", "features_path": f"{root}/features.npy"}
                open(f"{HERE}/ladder/geom/{name}_{split}.yml", "w").write(
                    f"# GENERATED by generate_ladder_all.py: {name}, {split} feature pass\n" + yaml.safe_dump(e, sort_keys=False))
            print(name, "warmup", lr.get("margin_warmup_epochs"))
