"""Eval-only feature passes for the ConvNeXt / DINOv2 models (geometry in the supplement).

For every finished Part 4 model, writes two configs from its training config:
  geom/<name>_val.yml    validation images -> PHASE4_GEOM/<name>/{features.npy, predictions.npz}
  geom/<name>_train.yml  training images   -> PHASE4_GEOM_TRAIN/<name>/{features.npy, predictions.npz}
Changes from the training config: do_train off, W&B off, no resume, init_weights = the run's final
model.safetensors, features and predictions saved; the train config evaluates train_2022.json
(eval transforms, one forward pass per image) with a larger eval batch.
NormFace (<backbone>_cosine_m0) is derived from the ArcFace config with m=0, since its own config
lives on its training branch; the margin is not used at evaluation anyway.
Run: python finetuning/SWIN/configs_advanced/backbones/generate_geom.py
"""
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = "/projectnb/herbdl/workspaces/faridkar/herbdl/finetuning/output"
TRAIN_JSON = "/projectnb/herbdl/data/kaggle-herbaria/train_2022.json"
NAMES = [f"{b}_{l}" for b in ("convnext", "dinov2") for l in ("ce", "ce_la", "arcface", "dbm", "cosine_m0")]

os.makedirs(f"{HERE}/geom", exist_ok=True)
for name in NAMES:
    src = name.replace("cosine_m0", "arcface")
    for split in ("val", "train"):
        c = yaml.safe_load(open(f"{HERE}/{src}.yml"))
        if name.endswith("cosine_m0"):
            c["loss_registry"]["head_kwargs"]["m"] = 0.0
            c["loss_registry"].pop("margin_warmup_epochs", None)
        root = f"{OUT}/SWIN/PHASE4_GEOM" + ("" if split == "val" else "_TRAIN") + f"/{name}"
        t = c["training"]
        t.update(do_train=False, do_eval=True, report_to="none", resume_from_checkpoint=None,
                 output_dir=root, logging_dir=root)
        if split == "train":
            c["data"]["validation_file"] = TRAIN_JSON
            t["per_device_eval_batch_size"] = 128
        c["wandb"]["enabled"] = False
        c["custom"]["run_notes"] = f"Eval-only feature pass of {name} on the {split} split (supplement geometry)."
        c["evaluation"] = {"init_weights": f"{OUT}/BACKBONES/{name}/model.safetensors",
                           "predictions_path": f"{root}/predictions.npz",
                           "features_path": f"{root}/features.npy"}
        with open(f"{HERE}/geom/{name}_{split}.yml", "w") as fh:
            fh.write(f"# GENERATED by generate_geom.py: eval-only feature pass of {name}, {split} split\n")
            fh.write(yaml.safe_dump(c, sort_keys=False))
        print(f"geom/{name}_{split}.yml")
