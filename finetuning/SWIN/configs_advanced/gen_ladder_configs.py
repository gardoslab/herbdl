"""Generate the Phase 6 scaling-ladder configs from the DBM pilot config.
Run from finetuning/SWIN/configs_advanced/:  python3 gen_ladder_configs.py"""
import re

BASE = open("swin_base_384_dbm_pilot.yml").read()
LADDER = "/projectnb/herbdl/workspaces/faridkar/herbdl/data/ladder"
OUT = "/projectnb/herbdl/workspaces/faridkar/herbdl/finetuning/output/SWIN"
HEADS = {
    "dbm": "  head: dbm\n  head_kwargs:\n    s: 30.0\n",
    # registry ArcMarginHead, same settings as the ArcFace+ECC/TARA runs: only the head
    # differs from the DBM runs (same code path, data, schedule, seed)
    "arcface": "  head: arcface\n  head_kwargs:\n    s: 30.0\n    m: 0.30\n",
}


def make(rung, loss, smoke=False):
    s = BASE
    tag = f"LADDER_{rung.upper()}_{loss.upper()}" + ("_SMOKE" if smoke else "")
    sub = {
        r'(?m)^  train_file: "[^"]+"': f'  train_file: "{LADDER}/{rung}_train.json"',
        r'(?m)^  validation_file: "[^"]+"': f'  validation_file: "{LADDER}/{rung}_val.json"',
        r'(?m)^  image_column_name: "[^"]+"': '  image_column_name: "filepath"',
        r'(?m)^  (output|logging)_dir: "[^"]+"': rf'  \1_dir: "{OUT}/SWIN_BASE_{tag}"',
        r'(?m)^  num_train_epochs: 50\s*$': "  num_train_epochs: 50   # ignored: max_steps below fixes the budget\n"
                                           "  max_steps: %d" % (40 if smoke else 131250)
                                           + ("   # smoke test" if smoke else "   # = the 15k runs' 50 epochs x 2,625 steps: same compute at every rung"),
        r'(?m)^  eval_steps: \d+\s*$': "  eval_steps: %d" % (20 if smoke else 26250),
        r'(?m)^  save_total_limit: \d+\s*$': "  save_total_limit: 3",
        r'(?m)^  run_group: "[^"]+"': f'  run_group: "SWIN_Base_{tag}"',
        r'(?m)^  run_name: "[^"]+"': f'  run_name: "SWIN_Base_{tag}"',
        r'(?m)^  run_id: "[^"]+"': f'  run_id: "swin_base_{tag.lower()}"',
        r'(?ms)^  head: dbm\n  head_kwargs:\n    s: 30\.0\n': HEADS[loss],
    }
    for pat, rep in sub.items():
        s, n = re.subn(pat, rep, s)
        assert n >= 1, (rung, loss, pat)
    if smoke:
        s, n = re.subn(r'(?m)^  max_eval_samples: null', "  max_eval_samples: 4000", s); assert n == 1
        s, n = re.subn(r'(?m)^  warmup_steps: \d+', "  warmup_steps: 5", s); assert n == 1
        s, n = re.subn(r'(?m)^  overwrite_output_dir: false', "  overwrite_output_dir: true", s); assert n == 1
        s, n = re.subn(r'(?m)^  report_to: "wandb"', '  report_to: "none"', s); assert n == 1
        s = s.replace('wandb:\n  enabled: true', 'wandb:\n  enabled: false')
    else:
        if "resume_from_checkpoint" not in s:
            s = s.replace("  overwrite_output_dir: false\n", "  overwrite_output_dir: false\n  resume_from_checkpoint: newest\n", 1)
    # drop the DBM pilot's own header comment block, add a ladder one
    s = re.sub(r"\A(#[^\n]*\n)+", "", s)
    head = (f"# Phase 6 scaling ladder: {loss.upper()} at the {rung} rung "
            f"({'SMOKE TEST, 40 steps' if smoke else '131,250 steps, 2 GPUs'}).\n"
            "# Generated by gen_ladder_configs.py from swin_base_384_dbm_pilot.yml; data from\n"
            "# loss_ablation/build_ladder.py (nested species sets cut from the merged 2021+2022 manifest).\n")
    name = f"swin_base_384_ladder_{'smoke' if smoke else rung + '_' + loss}.yml"
    open(name, "w").write(head + s)
    print(name)


for rung in ("n15k", "n64k"):
    for loss in ("dbm", "arcface"):
        make(rung, loss)
make("n64k", "dbm", smoke=True)
